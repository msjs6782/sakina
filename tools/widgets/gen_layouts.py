#!/usr/bin/env python3
"""Writes the home-screen widget layouts (app/src/main/res/layout/w_*.xml).

The layouts are plain RemoteViews layouts (FrameLayout, LinearLayout, TextView, ImageView, TextClock,
AnalogClock only). Each starts with a background and a border image that the app tints at runtime, so
colours, opacity, corners and borders are per widget; a painted sky and its veil can replace the colour. Default texts come from string resources and are
what the launcher's preview (previewLayout, Android 12+) shows. Sizes and colours are set at runtime.
Run from the repository root after changing it: python3 tools/widgets/gen_layouts.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "app/src/main/res/layout"
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'
PRAYERS = ["fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha"]


def frame(body, glass=False, msg_style="W.Text"):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/widgets/gen_layouts.py -->
<FrameLayout {NS}
    android:id="@+id/w_root"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:clipToOutline="true">

    <ImageView
        android:id="@+id/w_bg"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:importantForAccessibility="no"
        android:scaleType="fitXY"
        android:src="@drawable/w_shape_16"{' android:tint="#73000000" android:tintMode="src_in"' if glass else ''} />

    <ImageView
        android:id="@+id/w_sky"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:importantForAccessibility="no"
        android:scaleType="centerCrop"
        android:visibility="gone" />

    <ImageView
        android:id="@+id/w_scrim"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:importantForAccessibility="no"
        android:scaleType="fitXY"
        android:src="@drawable/w_scrim"
        android:visibility="gone" />

    <ImageView
        android:id="@+id/w_border"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:importantForAccessibility="no"
        android:scaleType="fitXY"
        android:src="@drawable/w_stroke_16_1"
        android:visibility="gone" />
{body}
    <TextView
        android:id="@+id/w_msg"
        style="@style/{msg_style}"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:gravity="center"
        android:maxLines="4"
        android:padding="12dp"
        android:textAlignment="center"
        android:visibility="gone" />
</FrameLayout>
'''


def text(id_, style, text_res, width="match_parent", extra=""):
    w = 'android:layout_width="0dp"\n            android:layout_weight="1"' if width == "weight" else f'android:layout_width="{width}"'
    return f'''
        <TextView
            android:id="@+id/{id_}"
            style="@style/{style}"
            {w}
            android:layout_height="wrap_content"
            android:text="@string/{text_res}"{extra} />'''


def refresh_row(place_style="W.Text.Small"):
    return f'''
        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:gravity="center_vertical"
            android:orientation="horizontal">
{indent(text("w_place", place_style, "w_sample_place", "weight"))}

            <ImageView
                android:id="@+id/w_refresh"
                android:layout_width="22dp"
                android:layout_height="22dp"
                android:contentDescription="@string/w_refresh"
                android:padding="2dp"
                android:src="@drawable/w_ic_refresh" />
        </LinearLayout>'''


def indent(s, n=4):
    return "\n".join((" " * n + l) if l.strip() else l for l in s.split("\n"))


def content(inner, gravity="center_vertical", orientation="vertical"):
    return f'''
    <LinearLayout
        android:id="@+id/w_content"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:gravity="{gravity}"
        android:orientation="{orientation}"
        android:padding="12dp">
{inner}
    </LinearLayout>
'''


def cells(style_name="W.Cell", style_time="W.Cell.Time", vertical=False):
    """Six prayer cells, each with a highlight pill behind it (shown for the next prayer)."""
    out = []
    for i, p in enumerate(PRAYERS):
        if vertical:
            cell = f'''
            <FrameLayout
                android:id="@+id/w_cell{i}"
                android:layout_width="match_parent"
                android:layout_height="0dp"
                android:layout_weight="1">

                <ImageView
                    android:id="@+id/w_hl{i}"
                    android:layout_width="match_parent"
                    android:layout_height="match_parent"
                    android:importantForAccessibility="no"
                    android:scaleType="fitXY"
                    android:src="@drawable/w_pill"
                    android:visibility="{'visible' if p == 'asr' else 'invisible'}" />

                <LinearLayout
                    android:layout_width="match_parent"
                    android:layout_height="match_parent"
                    android:gravity="center_vertical"
                    android:orientation="horizontal"
                    android:paddingStart="8dp"
                    android:paddingEnd="8dp">

                    <TextView
                        android:id="@+id/w_n{i}"
                        style="@style/{style_name}"
                        android:layout_width="0dp"
                        android:layout_height="wrap_content"
                        android:layout_weight="1"
                        android:gravity="start|center_vertical"
                        android:textAlignment="viewStart"
                        android:text="@string/w_sample_{p}" />

                    <TextView
                        android:id="@+id/w_t{i}"
                        style="@style/{style_time}"
                        android:layout_width="wrap_content"
                        android:layout_height="wrap_content"
                        android:text="@string/w_sample_t_{p}" />
                </LinearLayout>
            </FrameLayout>'''
        else:
            cell = f'''
            <FrameLayout
                android:id="@+id/w_cell{i}"
                android:layout_width="0dp"
                android:layout_height="match_parent"
                android:layout_weight="1">

                <ImageView
                    android:id="@+id/w_hl{i}"
                    android:layout_width="match_parent"
                    android:layout_height="match_parent"
                    android:importantForAccessibility="no"
                    android:scaleType="fitXY"
                    android:src="@drawable/w_pill"
                    android:visibility="{'visible' if p == 'asr' else 'invisible'}" />

                <LinearLayout
                    android:layout_width="match_parent"
                    android:layout_height="match_parent"
                    android:gravity="center"
                    android:orientation="vertical">

                    <TextView
                        android:id="@+id/w_n{i}"
                        style="@style/{style_name}"
                        android:layout_width="match_parent"
                        android:layout_height="wrap_content"
                        android:text="@string/w_sample_{p}" />

                    <TextView
                        android:id="@+id/w_t{i}"
                        style="@style/{style_time}"
                        android:layout_width="match_parent"
                        android:layout_height="wrap_content"
                        android:text="@string/w_sample_t_{p}" />
                </LinearLayout>
            </FrameLayout>'''
        out.append(cell)
    orient = "vertical" if vertical else "horizontal"
    return f'''
        <LinearLayout
            android:id="@+id/w_cells"
            android:layout_width="match_parent"
            android:layout_height="0dp"
            android:layout_weight="1"
            android:orientation="{orient}">
{"".join(out)}
        </LinearLayout>'''


def name_time_row(style="W.Text.Title"):
    return f'''
        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:gravity="center_vertical"
            android:orientation="horizontal">
{indent(text("w_name", style, "w_sample_name", "weight"))}
{indent(text("w_time", style, "w_sample_time", "wrap_content"))}
        </LinearLayout>'''


LAYOUTS = {}

# 1. Next prayer, wide: place and refresh; name and time on one line; remaining with its update time.
LAYOUTS["w_next_wide"] = frame(content(refresh_row() + name_time_row() + text("w_remain", "W.Text", "w_sample_remain_stamp")))
# 1b. Next prayer, narrow or tall: one item per line.
LAYOUTS["w_next_tall"] = frame(content(refresh_row() + text("w_name", "W.Text.Title", "w_sample_name") + text("w_time", "W.Text.Title", "w_sample_time")
                                       + text("w_remain", "W.Text", "w_sample_remain") + text("w_stamp", "W.Text.Small", "w_sample_stamp")))
# 2. Big remaining time with the absolute time.
LAYOUTS["w_countdown"] = frame(content(
    refresh_row() + text("w_label", "W.Text.Medium", "w_sample_until", extra='\n            android:gravity="center"\n            android:textAlignment="center"')
    + text("w_big", "W.Text.Big", "w_sample_big")
    + text("w_time", "W.Text.Medium", "w_sample_name_time", extra='\n            android:gravity="center"\n            android:textAlignment="center"')
    + text("w_stamp", "W.Text.Small", "w_sample_stamp", extra='\n            android:gravity="center"\n            android:textAlignment="center"')))
# 3. The day's five prayers and sunrise: columns (wide) or rows (tall).
LAYOUTS["w_day_wide"] = frame(content(refresh_row() + cells() + text("w_remain", "W.Text.Small", "w_sample_remain_stamp")))
LAYOUTS["w_day_tall"] = frame(content(refresh_row() + cells("W.Text", "W.Text.Medium", vertical=True) + text("w_remain", "W.Text.Small", "w_sample_remain_stamp")))
# 4. Glass panel (dark scrim, light text) and its light variant.
for tone, st in (("dark", "W.Glass"), ("light", "W.Glass.Light")):
    glass_cells = cells(st, st).replace(f'style="@style/{st}"', f'style="@style/{st}"\n                        android:gravity="center"\n                        android:textAlignment="center"\n                        android:ellipsize="none"')
    LAYOUTS[f"w_glass_{tone}"] = frame(content(refresh_row(st) + name_time_row(st) + text("w_remain", st, "w_sample_remain_stamp") + glass_cells),
                                        glass=True, msg_style=st)
# 5. Mini square: name over time.
LAYOUTS["w_mini"] = frame(content(
    text("w_name", "W.Text.Medium", "w_sample_name", extra='\n            android:gravity="center"\n            android:textAlignment="center"')
    + text("w_time", "W.Text.Title", "w_sample_time_short", extra='\n            android:gravity="center"\n            android:textAlignment="center"'),
    gravity="center"))
# 6. Horizontal strip of the six times.
LAYOUTS["w_strip"] = frame(content(cells(), gravity="center"))
# 7. Native digital clock with prayer context.
LAYOUTS["w_digital"] = frame(content(refresh_row() + '''
        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:gravity="center"
            android:orientation="horizontal">

            <TextClock
                android:id="@+id/w_clock"
                style="@style/W.Text.Big"
                android:layout_width="wrap_content"
                android:layout_height="wrap_content"
                android:format12Hour="h:mm"
                android:format24Hour="HH:mm" />

            <TextClock
                android:id="@+id/w_ampm"
                style="@style/W.Text.Medium"
                android:layout_width="wrap_content"
                android:layout_height="wrap_content"
                android:layout_marginStart="4dp"
                android:format12Hour="a"
                android:format24Hour="a" />
        </LinearLayout>''' + text("w_date", "W.Text.Small", "w_sample_date", extra='\n            android:gravity="center"\n            android:textAlignment="center"')
    + text("w_remain", "W.Text.Medium", "w_sample_name_time_remain", extra='\n            android:gravity="center"\n            android:textAlignment="center"')
    + text("w_stamp", "W.Text.Small", "w_sample_stamp", extra='\n            android:gravity="center"\n            android:textAlignment="center"')))
# 8. Native analog clock over a face with prayer marks (dark and light hands).
for tone in ("dark", "light"):
    LAYOUTS[f"w_analog_{tone}"] = frame(content('''
        <FrameLayout
            android:layout_width="match_parent"
            android:layout_height="0dp"
            android:layout_weight="1">

            <ImageView
                android:id="@+id/w_dial"
                android:layout_width="match_parent"
                android:layout_height="match_parent"
                android:importantForAccessibility="no"
                android:scaleType="fitCenter" />

            <AnalogClock
                android:id="@+id/w_clock"
                android:layout_width="match_parent"
                android:layout_height="match_parent"
                android:dial="@drawable/w_dial_blank"
                android:hand_hour="@drawable/w_hand_hour_%s"
                android:hand_minute="@drawable/w_hand_minute_%s" />
        </FrameLayout>''' % (tone, tone) + text("w_name", "W.Text.Medium", "w_sample_name_time", extra='\n            android:gravity="center"\n            android:textAlignment="center"')
        + text("w_place", "W.Text.Small", "w_sample_place", extra='\n            android:gravity="center"\n            android:textAlignment="center"'), gravity="center"))
# 9. Content card: a short dhikr or a selected verse with its reference.
LAYOUTS["w_content"] = frame(content('''
        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:gravity="center_vertical"
            android:orientation="horizontal">
''' + indent(text("w_label", "W.Text.Small", "w_sample_label_ayah", "weight")) + '''

            <ImageView
                android:id="@+id/w_next_btn"
                android:layout_width="22dp"
                android:layout_height="22dp"
                android:contentDescription="@string/w_next_item"
                android:padding="2dp"
                android:src="@drawable/w_ic_next" />
        </LinearLayout>

        <FrameLayout
            android:layout_width="match_parent"
            android:layout_height="0dp"
            android:layout_weight="1">

            <TextView
                android:id="@+id/w_text_ayah"
                android:layout_width="match_parent"
                android:layout_height="match_parent"
                android:fontFamily="@font/amiri_quran"
                android:gravity="center"
                android:lineSpacingMultiplier="1.1"
                android:text="@string/w_sample_ayah"
                android:textAlignment="center"
                android:textColor="#FF1C1B17"
                android:textSize="20sp" />

            <TextView
                android:id="@+id/w_text_dhikr"
                android:layout_width="match_parent"
                android:layout_height="match_parent"
                android:fontFamily="@font/amiri_regular"
                android:gravity="center"
                android:lineSpacingMultiplier="1.1"
                android:textAlignment="center"
                android:textColor="#FF1C1B17"
                android:textSize="20sp"
                android:visibility="gone" />
        </FrameLayout>''' + text("w_source", "W.Text.Small", "w_sample_source_ayah", extra='\n            android:gravity="center"\n            android:textAlignment="center"')))
# 10. Fajr and Maghrib with the Hijri date and the Ramadan context.
LAYOUTS["w_fajr_maghrib"] = frame(content(refresh_row() + '''
        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:orientation="horizontal">

            <LinearLayout
                android:layout_width="0dp"
                android:layout_height="wrap_content"
                android:layout_weight="1"
                android:gravity="center"
                android:orientation="vertical">
''' + indent(text("w_fajr_label", "W.Text.Medium", "w_sample_fajr", extra='\n            android:gravity="center"\n            android:textAlignment="center"'), 8) + '''
''' + indent(text("w_fajr_time", "W.Text.Title", "w_sample_t_fajr_full", extra='\n            android:gravity="center"\n            android:textAlignment="center"'), 8) + '''
            </LinearLayout>

            <LinearLayout
                android:layout_width="0dp"
                android:layout_height="wrap_content"
                android:layout_weight="1"
                android:gravity="center"
                android:orientation="vertical">
''' + indent(text("w_maghrib_label", "W.Text.Medium", "w_sample_maghrib", extra='\n            android:gravity="center"\n            android:textAlignment="center"'), 8) + '''
''' + indent(text("w_maghrib_time", "W.Text.Title", "w_sample_t_maghrib_full", extra='\n            android:gravity="center"\n            android:textAlignment="center"'), 8) + '''
            </LinearLayout>
        </LinearLayout>''' + text("w_hijri", "W.Text", "w_sample_hijri", extra='\n            android:gravity="center"\n            android:textAlignment="center"')
    + text("w_ramadan", "W.Text.Medium", "w_sample_ramadan", extra='\n            android:gravity="center"\n            android:textAlignment="center"')
    + text("w_stamp", "W.Text.Small", "w_sample_stamp", extra='\n            android:gravity="center"\n            android:textAlignment="center"')))

# 11. The day's name stretched with kashida across the widget, the dates above it, the prayers and the time left.
LAYOUTS["w_dayname"] = frame(content('''
        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:gravity="center_vertical"
            android:orientation="horizontal">

            <ImageView
                android:id="@+id/w_lead"
                android:layout_width="22dp"
                android:layout_height="22dp"
                android:importantForAccessibility="no" />
''' + indent(text("w_place", "W.Text.Small", "w_sample_dates", "weight", extra='\n            android:gravity="center"\n            android:textAlignment="center"')) + '''

            <ImageView
                android:id="@+id/w_refresh"
                android:layout_width="22dp"
                android:layout_height="22dp"
                android:contentDescription="@string/w_refresh"
                android:padding="2dp"
                android:src="@drawable/w_ic_refresh" />
        </LinearLayout>''' + text("w_dayname", "W.Day", "w_sample_dayname") + cells()
    + text("w_remain", "W.Text.Small", "w_sample_left_until")))


def kufi(xml):
    """The same layout in Noto Kufi Arabic: every W.* style becomes its WK.* copy (the day name keeps its font)."""
    return xml.replace('style="@style/W.', 'style="@style/WK.').replace("@style/WK.Day", "@style/W.Day")


for name, xml in list(LAYOUTS.items()):
    LAYOUTS[name + "_k"] = kufi(xml)

for name, xml in LAYOUTS.items():
    (OUT / f"{name}.xml").write_text(xml, encoding="utf-8")
print(f"wrote {len(LAYOUTS)} layouts to {OUT}")
